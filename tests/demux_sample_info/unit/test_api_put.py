"""Tests for the PUT (manual edit) workflow.

These tests verify the manual update path used by the GUI editor:
- raw_samplesheet_settings is always present on the new settings version
  (preserved for existing samples, backfilled when missing, initialized
  from config defaults for manually added samples)
- manual edits set auto_run=True in the version history (downstream tools
  require the field to be present and to trigger an automatic run for now)
"""

import copy
import unittest
from unittest.mock import MagicMock

import tornado.web
from tornado.escape import json_decode, json_encode
from tornado.testing import AsyncHTTPTestCase

from status.demux_sample_info import DemuxSampleInfoDataHandler
from tests.demux_sample_info.conftest import setup_mock_demux_config

EXISTING_UUID = "11111111-2222-3333-4444-555555555555"
MISSING_SETTINGS_UUID = "66666666-7777-8888-9999-000000000000"
NEW_UUID = "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee"

ORIGINAL_TS = "2025-01-01T10:00:00.000Z"

# Config defaults that should be applied to samples missing the field
CONFIG_DEFAULTS = {
    "Read1Cycles": {"default": 151},
    "Read2Cycles": {"default": 151},
    "TrimUMI": {"default": False},
}

EXPECTED_DEFAULT_SETTINGS = {
    "Read1Cycles": 151,
    "Read2Cycles": 151,
    "TrimUMI": False,
}

MOCK_CONFIG = {
    "bcl_convert_settings": {"raw_samplesheet_settings": CONFIG_DEFAULTS},
}


def _settings_entry(raw_settings):
    """Build a settings version entry."""
    return {
        "per_sample_fields": {
            "Lane": 1,
            "Sample_ID": "Sample_P101",
            "Sample_Name": "P101",
            "Sample_Project": "P101",
            "index": "AAAA",
            "index2": "GGGG",
            "OverrideCycles": "",
        },
        "other_details": {
            "sample_ref": "hg38",
            "sample_type": "standard",
            "named_index": "",
            "recipe": "151-8-8-151",
            "operator": "test",
            "index_length": [4, 4],
            "umi_config": None,
            "config_sources": ["test_source"],
        },
        "raw_samplesheet_settings": copy.deepcopy(raw_settings),
        "samplesheet_settings": copy.deepcopy(raw_settings),
    }


def _make_existing_document():
    """Existing document with one sample that has raw_samplesheet_settings
    and one sample whose stored settings are missing the field entirely."""
    doc_missing = _settings_entry({"Read1Cycles": 151, "Read2Cycles": 151})
    # Simulate a document created before raw_samplesheet_settings existed
    del doc_missing["raw_samplesheet_settings"]

    return {
        "_id": "TEST_FC_001",
        "_rev": "1-abc123",
        "flowcell_id": "TEST_FC_001",
        "metadata": {
            "num_lanes": 1,
            "run_setup": "151-8-8-151",
            "setup_lims_step_id": "24-123456",
            "first_generated": ORIGINAL_TS,
        },
        "calculated": {
            "version_history": {
                ORIGINAL_TS: {
                    "generated_by": "test@science.se",
                    "autogenerated": True,
                    "comment": "Uploaded from LIMS",
                    "auto_run": True,
                    "config_version": "test_version",
                }
            },
            "lanes": {
                "1": {
                    "sample_rows": {
                        EXISTING_UUID: {
                            "last_modified": ORIGINAL_TS,
                            "control": "N",
                            "description": "Test sample",
                            "project_id": "P101",
                            "project_name": "P101",
                            "library_method": "WGS",
                            "flowcell_id": "TEST_FC_001",
                            "settings": {
                                ORIGINAL_TS: _settings_entry(
                                    {"Read1Cycles": 100, "Read2Cycles": 100}
                                )
                            },
                        },
                        MISSING_SETTINGS_UUID: {
                            "last_modified": ORIGINAL_TS,
                            "control": "N",
                            "description": "Legacy sample",
                            "project_id": "P102",
                            "project_name": "P102",
                            "library_method": "",
                            "flowcell_id": "TEST_FC_001",
                            "settings": {ORIGINAL_TS: doc_missing},
                        },
                    }
                }
            },
        },
        "samplesheets": [],
        "config_version": "test_version",
    }


class TestPutManualEdit(AsyncHTTPTestCase):
    """Test the PUT endpoint used for manual edits from the GUI editor."""

    def get_app(self):
        return tornado.web.Application(
            [
                (r"/api/v1/demux_sample_info/([^/]*)", DemuxSampleInfoDataHandler),
            ]
        )

    def setUp(self):
        super().setUp()
        self._app.cloudant = MagicMock()
        self._app.gs_globals = {}
        self._app.test_mode = True
        setup_mock_demux_config(
            self._app.cloudant,
            config=MOCK_CONFIG,
            version="test_version",
            config_id="test_config_id",
        )
        self._document = _make_existing_document()
        self._mock_document_views()

    def _mock_document_views(self):
        """Mock the demux_sample_info document views and write operations."""
        config_side_effect = self._app.cloudant.post_view.side_effect

        def post_view(db, ddoc, view, **kwargs):
            if db == "demux_sample_info" and view == "flowcell_id":
                result = MagicMock()
                result.get_result.return_value = {
                    "rows": [{"id": "TEST_FC_001", "doc": self._document}]
                }
                return result
            return config_side_effect(db, ddoc, view, **kwargs)

        self._app.cloudant.post_view.side_effect = post_view

        self.posted_documents = []

        def post_document(db, document):
            self.posted_documents.append(document)
            result = MagicMock()
            result.get_result.return_value = {
                "ok": True,
                "id": document["_id"],
                "rev": "2-def456",
            }
            return result

        self._app.cloudant.post_document.side_effect = post_document

        def get_document(db, doc_id):
            doc = self.posted_documents[-1]
            result = MagicMock()
            result.get_result.return_value = {
                k: v for k, v in doc.items() if k not in ("_id", "_rev")
            }
            return result

        self._app.cloudant.get_document.side_effect = get_document

    def _put(self, samples, comment="test edit"):
        """Send a PUT with the given {uuid: fields} mapped to lane "1"."""
        response = self.fetch(
            "/api/v1/demux_sample_info/TEST_FC_001",
            method="PUT",
            body=json_encode(
                {
                    "flowcell_id": "TEST_FC_001",
                    "edited_settings": {"1": samples},
                    "comment": comment,
                }
            ),
            headers={"Content-Type": "application/json"},
        )
        return response

    def _latest_settings(self, document, lane, uuid):
        sample = document["calculated"]["lanes"][lane]["sample_rows"][uuid]
        latest_ts = max(sample["settings"].keys())
        return latest_ts, sample["settings"][latest_ts]

    def _latest_version_history(self, document):
        history = document["calculated"]["version_history"]
        latest_ts = max(k for k in history.keys() if k != ORIGINAL_TS)
        return latest_ts, history[latest_ts]

    def test_put_existing_sample_preserves_raw_samplesheet_settings(self):
        """Editing an existing sample must keep raw_samplesheet_settings intact."""
        response = self._put({EXISTING_UUID: {"sample_project": "NewProject"}})
        self.assertEqual(response.code, 200)

        document = json_decode(response.body)
        latest_ts, settings = self._latest_settings(document, "1", EXISTING_UUID)
        self.assertNotEqual(latest_ts, ORIGINAL_TS)
        # The original (non-default) values must be preserved, not overwritten
        self.assertEqual(
            settings["raw_samplesheet_settings"],
            {"Read1Cycles": 100, "Read2Cycles": 100},
        )
        # The edit itself must be applied
        self.assertEqual(settings["per_sample_fields"]["Sample_Project"], "NewProject")
        # samplesheet_settings must be recalculated from the stored raw settings
        self.assertEqual(settings["samplesheet_settings"]["Read1Cycles"], 100)

    def test_put_backfills_missing_raw_samplesheet_settings(self):
        """Samples whose stored settings lack raw_samplesheet_settings (legacy
        documents) must get the config defaults backfilled on manual edit."""
        response = self._put(
            {MISSING_SETTINGS_UUID: {"sample_project": "P102_updated"}}
        )
        self.assertEqual(response.code, 200)

        document = json_decode(response.body)
        _, settings = self._latest_settings(document, "1", MISSING_SETTINGS_UUID)
        self.assertIn("raw_samplesheet_settings", settings)
        self.assertEqual(
            settings["raw_samplesheet_settings"], EXPECTED_DEFAULT_SETTINGS
        )

    def test_put_new_sample_gets_config_default_raw_settings(self):
        """Manually added samples must be initialized with the config
        raw_samplesheet_settings defaults instead of an empty dict."""
        response = self._put(
            {
                NEW_UUID: {
                    "sample_id": "Sample_P999",
                    "sample_project": "P999",
                    "index": "TTTT",
                    "index2": "CCCC",
                }
            }
        )
        self.assertEqual(response.code, 200)

        document = json_decode(response.body)
        _, settings = self._latest_settings(document, "1", NEW_UUID)
        self.assertEqual(
            settings["raw_samplesheet_settings"], EXPECTED_DEFAULT_SETTINGS
        )
        # The generated samplesheet for the new sample must carry the
        # BCLConvert settings instead of an empty block
        matching_sheets = [
            sheet
            for sheet in document["samplesheets"]
            if any(
                sample.get("Sample_ID") == "Sample_P999"
                for sample in sheet["BCLConvert_Data"]
            )
        ]
        self.assertEqual(len(matching_sheets), 1)
        self.assertEqual(
            matching_sheets[0]["BCLConvert_Settings"], EXPECTED_DEFAULT_SETTINGS
        )

    def test_put_sets_auto_run_true(self):
        """Manual edits should set auto_run=True in the version history for now."""
        response = self._put({EXISTING_UUID: {"sample_project": "NewProject"}})
        self.assertEqual(response.code, 200)

        document = json_decode(response.body)
        _, entry = self._latest_version_history(document)
        self.assertTrue(entry["auto_run"])
        self.assertFalse(entry["autogenerated"])
        self.assertEqual(entry["comment"], "test edit")


if __name__ == "__main__":
    unittest.main()
